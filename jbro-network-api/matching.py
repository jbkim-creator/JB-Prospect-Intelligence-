"""Admin-only exact-MPN matching. Candidate ranking is not a verified trade."""
from datetime import date, datetime, timezone
from decimal import Decimal, InvalidOperation
import re
from flask import request, jsonify

MPN = re.compile(r"^[A-Z0-9][A-Z0-9._/+()-]{0,95}$")
CURRENCIES = {"USD", "KRW"}
FIELDS = ("line_key","side","mpn","manufacturer","quantity","currency","unit_price","basis","verification","valid_until","source_ref","case_key")
def normalize(data):
    if not isinstance(data,dict):
        raise ValueError("invalid_payload")
    def field(k,n,required=False):
        v=data.get(k,"")
        if not isinstance(v,str) or len(v.strip())>n or (required and not v.strip()):
            raise ValueError(k)
        return v.strip()
    key=field("line_key",64,True).upper()
    side=field("side",8,True)
    mpn=field("mpn",96,True).upper()
    maker=field("manufacturer",80).upper()
    if not re.fullmatch(r"[A-Z0-9][A-Z0-9_-]{2,63}",key) or side not in ("buy","sell") or not MPN.fullmatch(mpn):
        raise ValueError("invalid_key_side_or_mpn")
    qty=field("quantity",12)
    if qty and (not re.fullmatch(r"[0-9]{1,12}",qty) or int(qty)<=0):
        raise ValueError("invalid_quantity")
    cur=field("currency",3)
    raw=field("unit_price",24)
    if bool(cur)!=bool(raw) or (cur and cur not in CURRENCIES):
        raise ValueError("currency_price_pair")
    price=None
    if raw:
        if not re.fullmatch(r"[0-9]{1,10}(?:\.[0-9]{1,6})?",raw):
            raise ValueError("invalid_price")
        price=Decimal(raw)
        if price<=0:
            raise ValueError("invalid_price")
    basis=field("basis",120)
    verification=field("verification",20,True)
    if verification not in ("reported","document_reviewed"):
        raise ValueError("invalid_verification")
    until=field("valid_until",10)
    if until:
        try:
            until_date=date.fromisoformat(until)
            if until_date.isoformat()!=until: raise ValueError
        except ValueError:
            raise ValueError("invalid_valid_until") from None
    else: until_date=None
    source=field("source_ref",240,True)
    case=field("case_key",64,True).upper()
    if not re.fullmatch(r"[A-Z0-9][A-Z0-9_-]{2,63}",case):
        raise ValueError("invalid_case_key")
    return dict(line_key=key,side=side,mpn=mpn,manufacturer=maker,quantity=int(qty) if qty else None,
                currency=cur or None,unit_price=price,basis=basis,verification=verification,
                valid_until=until_date,source_ref=source,case_key=case)

def classify(b,s,today):
    if b["mpn"]!=s["mpn"]:
        return None
    if b["manufacturer"] and s["manufacturer"] and b["manufacturer"]!=s["manufacturer"]:
        return None
    flags=[]
    for name,l in (("buyer",b),("supplier",s)):
        if not l["manufacturer"]: flags.append(name+"_manufacturer_unknown")
        if not l["quantity"]: flags.append(name+"_quantity_unknown")
        if not l["valid_until"]: flags.append(name+"_validity_unknown")
        elif l["valid_until"]<today: flags.append(name+"_expired")
        if l["verification"]!="document_reviewed": flags.append(name+"_evidence_pending")
    qty=min(b["quantity"],s["quantity"]) if b["quantity"] and s["quantity"] else None
    if qty is not None and s["quantity"]<b["quantity"]: flags.append("partial_quantity")
    if b["unit_price"] is None or s["unit_price"] is None: flags.append("price_missing")
    elif b["currency"]!=s["currency"]: flags.append("currency_mismatch")
    elif not b["basis"] or b["basis"]!=s["basis"]: flags.append("price_basis_not_comparable")
    elif b["unit_price"]<s["unit_price"]: flags.append("price_gap")
    # Equal reported prices never establish financial feasibility: fees, shipping and compliance are outside this model.
    if any(x.endswith("_expired") for x in flags): status="expired"
    elif flags: status="review_required"
    else: status="commercial_candidate"
    return dict(buy_key=b["line_key"],sell_key=s["line_key"],mpn=b["mpn"],buy_case=b["case_key"],
                sell_case=s["case_key"],overlap_quantity=qty,status=status,flags=flags)

def ensure_schema(connection):
    with connection() as conn:
        conn.execute("""
        CREATE TABLE IF NOT EXISTS trade_match_lines(
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          line_key VARCHAR(64) UNIQUE NOT NULL,
          side VARCHAR(8) NOT NULL CHECK(side IN ('buy','sell')),
          mpn VARCHAR(96) NOT NULL,manufacturer VARCHAR(80) NOT NULL DEFAULT '',
          quantity BIGINT CHECK(quantity>0),currency VARCHAR(3),unit_price NUMERIC(16,6),
          basis VARCHAR(120) NOT NULL DEFAULT '',
          verification VARCHAR(20) NOT NULL CHECK(verification IN ('reported','document_reviewed')),
          valid_until DATE,source_ref VARCHAR(240) NOT NULL,
          case_key VARCHAR(64) NOT NULL REFERENCES closing_desk_cases(deal_key),
          active BOOLEAN NOT NULL DEFAULT TRUE,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
          CHECK ((currency IS NULL AND unit_price IS NULL) OR
                 (currency IN ('USD','KRW') AND unit_price IS NOT NULL AND unit_price>0))
        )""")
        conn.execute("CREATE INDEX IF NOT EXISTS trade_match_mpn_idx ON trade_match_lines(mpn,side) WHERE active")

def serialize(r):
    d=dict(r)
    for k in ("valid_until","created_at"):
        if d.get(k) is not None: d[k]=d[k].isoformat()
    if d.get("unit_price") is not None: d["unit_price"]=str(d["unit_price"])
    return d

def init(app,connection,authorized_admin):
    @app.route("/api/admin/matching/lines",methods=["GET","POST"])
    def matching_lines():
        if not authorized_admin(): return jsonify(error="unauthorized"),401
        if request.method=="POST":
            try: data=normalize(request.get_json(silent=True))
            except ValueError as e: return jsonify(error=str(e)),400
        try:
            ensure_schema(connection)
            with connection() as conn:
                if request.method=="GET":
                    rows=conn.execute("SELECT * FROM trade_match_lines ORDER BY id DESC LIMIT 200").fetchall()
                    return jsonify(lines=[serialize(r) for r in rows],limit=200)
                case=conn.execute("SELECT deal_key FROM closing_desk_cases WHERE deal_key=%s",(data["case_key"],)).fetchone()
                if not case: return jsonify(error="unknown_case_key"),400
                row=conn.execute("INSERT INTO trade_match_lines("+",".join(FIELDS)+") VALUES("+",".join(["%s"]*len(FIELDS))+") ON CONFLICT(line_key) DO NOTHING RETURNING *",tuple(data[k] for k in FIELDS)).fetchone()
                if not row: return jsonify(error="duplicate_line_key"),409
                return jsonify(line=serialize(row)),201
        except Exception:
            app.logger.warning("Matching line operation failed")
            return jsonify(error="temporarily_unavailable"),503

    @app.post("/api/admin/matching/lines/<int:line_id>/archive")
    def archive_matching_line(line_id):
        if not authorized_admin(): return jsonify(error="unauthorized"),401
        try:
            with connection() as conn:
                row=conn.execute("UPDATE trade_match_lines SET active=FALSE WHERE id=%s AND active RETURNING id",(line_id,)).fetchone()
                return (jsonify(archived=True),200) if row else (jsonify(error="not_found_or_archived"),404)
        except Exception:
            return jsonify(error="temporarily_unavailable"),503

    @app.get("/api/admin/matching/candidates")
    def matching_candidates():
        if not authorized_admin(): return jsonify(error="unauthorized"),401
        try:
            ensure_schema(connection)
            with connection() as conn:
                rows=conn.execute("""
                SELECT l.* FROM trade_match_lines l JOIN closing_desk_cases c ON c.deal_key=l.case_key
                WHERE l.active AND c.stage NOT IN ('lost','on_hold','handoff')
                ORDER BY l.id DESC LIMIT 500
                """).fetchall()
            buys=[r for r in rows if r["side"]=="buy"]
            supplies={}
            for r in rows:
                if r["side"]=="sell": supplies.setdefault(r["mpn"],[]).append(r)
            today=datetime.now(timezone.utc).date()
            matches=[m for b in buys for s in supplies.get(b["mpn"],[]) if (m:=classify(b,s,today)) is not None]
            priorities={"commercial_candidate":0,"review_required":1,"expired":2}
            matches.sort(key=lambda m:(priorities[m["status"]],len(m["flags"]),m["mpn"],m["buy_key"],m["sell_key"]))
            return jsonify(candidates=matches[:200],total_in_scope=len(matches),lines_in_scope=len(rows),
                           line_limit=500,candidate_limit=200,definition="Exact MPN candidates only, not AI inference, orders, GMV or compliance clearance.")
        except Exception:
            app.logger.warning("Matching candidate operation failed")
            return jsonify(error="temporarily_unavailable"),503
