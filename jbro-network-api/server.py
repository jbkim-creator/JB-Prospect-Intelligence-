def setup_db():
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
              CREATE TABLE IF NOT EXISTS partner_applications (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                organization VARCHAR(120) NOT NULL,
                email VARCHAR(160) NOT NULL,
                country VARCHAR(80),
                role VARCHAR(40) NOT NULL,
                summary VARCHAR(650) NOT NULL,
                status VARCHAR(24) NOT NULL DEFAULT 'pending',
                created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                reviewed_at TIMESTAMPTZ,
                CONSTRAINT partner_application_status CHECK (status IN ('pending','reviewing','approved','rejected'))
              )
            """)
            cur.execute("CREATE INDEX IF NOT EXISTS partner_applications_status_created ON partner_applications(status, created_at DESC)")
            cur.execute("""CREATE TABLE IF NOT EXISTS activity_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                entity_type VARCHAR(32) NOT NULL,
                entity_id BIGINT NOT NULL,
                action VARCHAR(40) NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )""")
            cur.execute("""CREATE TABLE IF NOT EXISTS partner_access (
                application_id BIGINT PRIMARY KEY REFERENCES partner_applications(id) ON DELETE CASCADE,
                token_sha256 CHAR(64) NOT NULL UNIQUE, issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                revoked_at TIMESTAMPTZ
            )""")
            cur.execute("""CREATE TABLE IF NOT EXISTS partner_opportunities (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                application_id BIGINT NOT NULL REFERENCES partner_applications(id),
                category VARCHAR(32) NOT NULL CHECK (category IN ('buy_requirement','stock_offer','industrial_asset','project_opportunity','service_capability')),
                title VARCHAR(160) NOT NULL, summary VARCHAR(1800) NOT NULL,
                country VARCHAR(80),
                status VARCHAR(24) NOT NULL DEFAULT 'submitted'
                CHECK (status IN ('submitted','reviewing','qualified','closed','rejected')),
                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )""")
            cur.execute("CREATE INDEX IF NOT EXISTS idx_partner_opportunities_owner_created ON partner_opportunities(application_id,created_at DESC)")

