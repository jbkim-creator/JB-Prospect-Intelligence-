import os
import re
import json
import time
import hmac
import hashlib
import logging
from datetime import datetime, timezone
from flask import Flask, request, jsonify, make_response
from psycopg import connect
from psycopg.rows import dict_row

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = 8192
logging.basicConfig(level=logging.INFO)
ALLOWED_ORIGIN = "https://jbro-global-network.onrender.com"
DB_URL = os.getenv("DATABASE_URL", "")
ADMIN_TOKEN = os.getenv("JBRO_ADMIN_TOKEN", "")
ROLES = {"Buyer","Supplier","Opportunity contributor","Execution partner","Regional partner","Service partner"}
MAX_PER_HOUR = 6
_hits = {}

def connection():
    if not DB_URL:
        raise RuntimeError("Database configuration unavailable")
    return connect(DB_URL, row_factory=dict_row, connect_timeout=5)

def setup_db():
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
              CREATE TABLE IF NOT EXISTS partner_applications (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                organization VARCHAR(120) NOT NULL,
                email VARCHAR(160) NOT NULL,
                country VARCHAR(80),
                role VARCHAR(40) NOT NULL,
                summary VARCHAR(650) NOT NULL,
                status VARCHAR(24) NOT NULL DEFAULT 'pending',
                created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                reviewed_at TIMESTAMPTZ,
                CONSTRAINT partner_application_status CHECK (status IN ('pending','reviewing','approved','rejected'))
              )
            """)
            cur.execute("CREATE INDEX IF NOT EXISTS partner_applications_status_created ON partner_applications(status, created_at DESC)")
            cur.execute("""CREATE TABLE IF NOT EXISTS activity_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                entity_type VARCHAR(32) NOT NULL,
                entity_id BIGINT NOT NULL,
                action VARCHAR(40) NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )""")

@app.after_request
def headers(response):
    response.headers["Cache-Control"] = "no-store"
    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["Referrer-Policy"] = "no-referrer"
    response.headers["Content-Security-Policy"] = "default-src 'none'; frame-ancestors 'none'"
    if request.headers.get("Origin") == ALLOWED_ORIGIN:
        response.headers["Access-Control-Allow-Origin"] = ALLOWED_ORIGIN
        response.headers["Access-Control-Allow-Methods"] = "POST, OPTIONS"
        response.headers["Access-Control-Allow-Headers"] = "Content-Type"
        response.headers["Vary"] = "Origin"
    return response

@app.get("/healthz")
def health():
    return jsonify(status="up", database_configured=bool(DB_URL))

@app.get("/readyz")
def ready():
    try:
        setup_db()
        with connection() as c:
            c.execute("SELECT 1")
        return jsonify(status="ready")
    except Exception:
        app.logger.warning("Readiness failed; check DB connection settings")
        return jsonify(status="not_ready"),503

@app.route("/api/partner-applications", methods=["POST","OPTIONS"])
def intake():
    if request.method == "OPTIONS":
        return make_response("", 204)
    if request.headers.get("Origin") != ALLOWED_ORIGIN:
        return jsonify(error="origin_not_allowed"),403
    if not request.is_json:
        return jsonify(error="json_required"),415
    if not DB_URL:
        return jsonify(error="temporarily_unavailable"),503
    data=request.get_json(silent=True)
    if not isinstance(data,dict):
        return jsonify(error="invalid_payload"),400
    if data.get("website"):
        return jsonify(status="received"),202
    org=str(data.get("organization","")).strip()
    email=str(data.get("email","")).strip().lower()
    country=str(data.get("country","")).strip()
    role=str(data.get("role","")).strip()
    summary=str(data.get("summary","")).strip()
    consent=data.get("consent") is True
    if not (1<=len(org)<=120 and len(country)<=80 and 10<=len(summary)<=650 and role in ROLES and consent and re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+",email) and len(email)<=160):
        return jsonify(error="invalid_fields"),400
    ip=request.headers.get("X-Forwarded-For",request.remote_addr or "").split(",")[0].strip()
    key=hashlib.sha256(ip.encode()).hexdigest()[:20]
    now=time.monotonic()
    hits=[v for v in _hits.get(key,[]) if now-v<3600]
    if len(hits)>=MAX_PER_HOUR:
        return jsonify(error="rate_limited"),429
    hits.append(now)
    _hits[key]=hits
    try:
        setup_db()
        with connection() as conn:
            with conn.cursor() as cur:
                cur.execute("INSERT INTO partner_applications(organization,email,country,role,summary) VALUES (%s,%s,%s,%s,%s) RETURNING id", (org,email,country,role,summary))
                application_id=cur.fetchone()["id"]
                cur.execute("INSERT INTO activity_events(entity_type,entity_id,action) VALUES ('partner_application',%s,'created')",(application_id,))
        return jsonify(status="received",reference=f"JBRO-P-{application_id:06d}"),201
    except Exception:
        app.logger.exception("Partner intake database failure")
        return jsonify(error="temporarily_unavailable"),503

def authorized_admin():
    if not ADMIN_TOKEN or len(ADMIN_TOKEN)<32:
        return False
    v=request.headers.get("Authorization","")
    return v.startswith("Bearer ") and hmac.compare_digest(v[7:],ADMIN_TOKEN)

@app.get("/api/admin/applications")
def list_applications():
    if not authorized_admin():
        return jsonify(error="unauthorized"),401
    try:
        with connection() as conn:
            rows=conn.execute("SELECT id,organization,email,country,role,summary,status,created_at FROM partner_applications ORDER BY created_at DESC LIMIT 100").fetchall()
        for row in rows:
            row["created_at"]=row["created_at"].isoformat()
        return jsonify(applications=rows)
    except Exception:
        return jsonify(error="temporarily_unavailable"),503

@app.patch("/api/admin/applications/<int:application_id>")
def update_application(application_id):
    if not authorized_admin():
        return jsonify(error="unauthorized"),401
    body=request.get_json(silent=True) or {}
    status=body.get("status")
    if status not in ("pending","reviewing","approved","rejected"):
        return jsonify(error="invalid_status"),400
    try:
        with connection() as conn:
            with conn.cursor() as cur:
                cur.execute("UPDATE partner_applications SET status=%s,reviewed_at=now() WHERE id=%s RETURNING id",(status,application_id))
                if cur.fetchone() is None:
                    return jsonify(error="not_found"),404
                cur.execute("INSERT INTO activity_events(entity_type,entity_id,action) VALUES ('partner_application',%s,%s)",(application_id,status))
        return jsonify(status=status,id=application_id)
    except Exception:
        return jsonify(error="temporarily_unavailable"),503

if __name__=="__main__":
    app.run(host="0.0.0.0",port=int(os.getenv("PORT",10000)))
