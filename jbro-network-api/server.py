@app.route("/api/partner-applications", methods=["POST","OPTIONS"])
def intake():
    if request.method == "OPTIONS":
        return make_response("", 204)
    if request.headers.get("Origin") != ALLOWED_ORIGIN:
        return jsonify(error="origin_not_allowed"),403
    if not request.is_json:
        return jsonify(error="json_required"),415
    if not DB_URL:
        return jsonify(error="temporarily_unavailable"),503
    data=request.get_json(silent=True)
    if not isinstance(data,dict):
        return jsonify(error="invalid_payload"),400
    if data.get("website"):
        return jsonify(status="received"),202
    org=str(data.get("organization","")).strip()
    email=str(data.get("email","")).strip().lower()
    country=str(data.get("country","")).strip()
    role=str(data.get("role","")).strip()
    summary=str(data.get("summary","")).strip()
    consent=data.get("consent") is True
    if not (1<=len(org)<=120 and len(country)<=80 and 10<=len(summary)<=650 and role in ROLES and consent and re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+",email) and len(email)<=160):
        return jsonify(error="invalid_fields"),400
    ip=request.headers.get("X-Forwarded-For",request.remote_addr or "").split(",")[0].strip()
    key=hashlib.sha256(ip.encode()).hexdigest()[:20]
    now=time.monotonic()
    hits=[v for v in _hits.get(key,[]) if now-v<3600]
    if len(hits)>=MAX_PER_HOUR:
        return jsonify(error="rate_limited"),429
    hits.append(now)
    _hits[key]=hits
    try:
        setup_db()
        with connection() as conn:
            with conn.cursor() as cur:
                cur.execute("INSERT INTO partner_applications(organization,email,country,role,summary) VALUES (%s,%s,%s,%s,%s) RETURNING id", (org,email,country,role,summary))
                application_id=cur.fetchone()["id"]
                cur.execute("INSERT INTO activity_events(entity_type,entity_id,action) VALUES ('partner_application',%s,'created')",(application_id,))
        return jsonify(status="received",reference=f"JBRO-P-{application_id:06d}"),201
    except Exception:
        app.logger.exception("Partner intake database failure")
        return jsonify(error="temporarily_unavailable"),503

def authorized_admin():
    if not ADMIN_TOKEN or len(ADMIN_TOKEN)<32:
        return False
    v=request.headers.get("Authorization","")
    return v.startswith("Bearer ") and hmac.compare_digest(v[7:],ADMIN_TOKEN)

@app.get("/api/admin/first10k-funnel")
def private_first10k_funnel():
    """Consented application-source aggregates; no public tracking, PII, or inferred sales."""
    if not authorized_admin():
        return jsonify(error="unauthorized"),401
    try:
        with connection() as conn:
            sources=conn.execute("""
              WITH leads AS (
                SELECT id,status,role,
                  COALESCE(NULLIF(substring(summary from '\\[Referral: ([A-Za-z0-9_-]{1,40})\\]'),''),'UNATTRIBUTED') AS source,
                  (summary LIKE '[FIRST10K coupon request]%') AS interested
                FROM partner_applications
              )
              SELECT l.source,
                count(DISTINCT l.id)::int AS applications,
                count(DISTINCT l.id) FILTER (WHERE l.interested)::int AS coupon_requests,
                count(DISTINCT l.id) FILTER (WHERE l.status='approved')::int AS approved_applications,
                count(DISTINCT l.id) FILTER (WHERE l.interested AND l.status='approved')::int AS approved_coupon_interest,
                count(DISTINCT p.id)::int AS issued_coupons
              FROM leads l
              LEFT JOIN promo_fee_coupons p ON p.application_id=l.id AND p.campaign='FIRST10K'
              GROUP BY l.source
              ORDER BY count(DISTINCT l.id) DESC,l.source ASC LIMIT 100
            """).fetchall()
            app_counts=conn.execute("""
              SELECT count(*)::int AS applications,
                count(*) FILTER (WHERE summary LIKE '[FIRST10K coupon request]%')::int AS coupon_requests,
                count(*) FILTER (WHERE status='approved')::int AS approved_applications
              FROM partner_applications
            """).fetchone()
            issued=conn.execute("""
              SELECT count(*)::int AS coupon_count,
                     COALESCE(sum(discount_won) FILTER (WHERE currency='USD'),0)::bigint AS waived_usd_minor
              FROM promo_fee_coupons WHERE campaign='FIRST10K'
            """).fetchone()
            completed=conn.execute("""
              WITH latest_stage AS (
                SELECT DISTINCT ON (room_id,stage) room_id,stage,status
                FROM deal_execution_events
                ORDER BY room_id,stage,created_at DESC,id DESC
              ), completed_rooms AS (
                SELECT dr.id,r.deal_value_won AS value_minor
                FROM deal_rooms dr
                JOIN reward_deals r ON r.id=dr.reward_deal_id AND r.currency='USD'
                WHERE EXISTS (
                  SELECT 1 FROM deal_sale_contracts c WHERE c.room_id=dr.id AND c.status='signed'
                )
                AND (SELECT count(*) FROM latest_stage s WHERE s.room_id=dr.id AND s.status='verified')=4
                AND NOT EXISTS (
                  SELECT 1 FROM latest_stage s WHERE s.room_id=dr.id AND s.status<>'verified'
                )
              )
              SELECT count(*)::int AS completed_coupon_deals,
                     COALESCE(sum(value_minor),0)::bigint AS completed_coupon_gmv_usd_minor
              FROM completed_rooms c
              WHERE EXISTS (
                SELECT 1 FROM promo_fee_coupons p WHERE p.deal_room_id=c.id
                AND p.campaign='FIRST10K' AND p.currency='USD'
              )
            """).fetchone()
        totals={
          "applications":int(app_counts["applications"]),
          "coupon_requests":int(app_counts["coupon_requests"]),
          "approved_applications":int(app_counts["approved_applications"]),
          "issued_coupons":int(issued["coupon_count"]),
          "waived_usd_minor":int(issued["waived_usd_minor"]),
          "completed_coupon_deals":int(completed["completed_coupon_deals"]),
          "completed_coupon_gmv_usd_minor":int(completed["completed_coupon_gmv_usd_minor"])
        }
        return jsonify(
            totals=totals,
            sources=[dict(v) for v in sources],
            definitions={
              "applications":"All submitted partner applications. Source extracted only from user-provided optional referral code.",
              "coupon_requests":"Applications that opted in with the FIRST10K coupon request tag; not approvals.",
              "approved_applications":"Approved partner applications, not approved coupons.",
              "issued_coupons":"Existing FIRST10K coupon issuance records; no coupon is automatically granted.",
              "waived_usd_minor":"Sum of recorded USD coupon discount in cents; not a cash marketing expense or JBRO fee receipt.",
              "completed_coupon_gmv_usd_minor":"Completed verified USD Deal Rooms linked to at least one issued FIRST10K coupon; counted once per deal. Association is not proof the coupon caused the transaction.",
              "attribution":"No visitor, click, conversion-rate, or email-open tracking. Codes can be user-entered and are not independently authenticated.",
              "privacy":"Admin-only grouped application counts, no names, emails, or customer identifiers."
            })
    except Exception:
        app.logger.exception("Private FIRST10K funnel read failed")
        return jsonify(error="temporarily_unavailable"),503

@app.get("/api/admin/gmv-kpis")
def private_gmv_kpis():
    """Read-only, admin-only trading KPIs. Never treat a quote or signed deal as completed GMV."""
    if not authorized_admin():
        return jsonify(error="unauthorized"),401
    try:
        with connection() as conn:
            rows=conn.execute("""
              WITH latest_stage AS (
                SELECT DISTINCT ON (room_id,stage) room_id,stage,status
                FROM deal_execution_events
                ORDER BY room_id,stage,created_at DESC,id DESC
              ), stages AS (
                SELECT room_id,
                  bool_and(status='verified') AND count(*)=4 AS all_verified
                FROM latest_stage
                GROUP BY room_id
              ), sale AS (
                SELECT r.id AS reward_deal_id,r.currency,r.deal_value_won AS value_minor,
                       dr.id AS room_id,
                       EXISTS (
                         SELECT 1 FROM deal_sale_contracts c
                         WHERE c.room_id=dr.id AND c.status='signed'
                       ) AS signed_contract,
                       COALESCE(st.all_verified,FALSE) AS fulfilled
                FROM reward_deals r
                JOIN deal_rooms dr ON dr.reward_deal_id=r.id
                LEFT JOIN stages st ON st.room_id=dr.id
              ), receipt AS (
                SELECT r.currency,COALESCE(sum(p.amount_won),0)::bigint AS receipts_minor,
                       count(p.id)::integer AS receipt_entries
                FROM reward_deals r
                JOIN reward_receipts p ON p.deal_id=r.id
                GROUP BY r.currency
              )
              SELECT s.currency,
                count(*) FILTER (WHERE s.signed_contract)::integer AS signed_deals,
                COALESCE(sum(s.value_minor) FILTER (WHERE s.signed_contract),0)::bigint AS signed_gmv_minor,
                count(*) FILTER (WHERE s.signed_contract AND s.fulfilled)::integer AS completed_deals,
                COALESCE(sum(s.value_minor) FILTER (WHERE s.signed_contract AND s.fulfilled),0)::bigint AS completed_gmv_minor,
                COALESCE(max(rc.receipts_minor),0)::bigint AS recorded_commission_minor,
                COALESCE(max(rc.receipt_entries),0)::integer AS receipt_entries
              FROM sale s LEFT JOIN receipt rc ON rc.currency=s.currency
              GROUP BY s.currency
            """).fetchall()
            # Receipts without linked sale rooms must still show as recorded fees, not GMV.
            receipt_rows=conn.execute("""
              SELECT r.currency,COALESCE(sum(p.amount_won),0)::bigint AS amount,
                     count(p.id)::integer AS entries
              FROM reward_receipts p JOIN reward_deals r ON r.id=p.deal_id
              GROUP BY r.currency
            """).fetchall()
            counts=conn.execute("""
              SELECT
                (SELECT count(*) FROM partner_applications WHERE status='approved') AS approved_partners,
                (SELECT count(*) FROM partner_opportunities WHERE status='qualified') AS qualified_opportunities,
                (SELECT count(*) FROM deal_rooms WHERE status='draft') AS draft_rooms,
                (SELECT count(*) FROM promo_fee_coupons WHERE campaign='FIRST10K') AS first10k_coupons
            """).fetchone()
        currencies={c:{"signed_deals":0,"signed_gmv_minor":0,"completed_deals":0,"completed_gmv_minor":0,"recorded_commission_minor":0,"receipt_entries":0} for c in ("USD","KRW")}
        for r in rows:
            c=r["currency"]
            if c not in currencies: continue
            for k in currencies[c]: currencies[c][k]=int(r[k])
        for r in receipt_rows:
            if r["currency"] in currencies:
                currencies[r["currency"]]["recorded_commission_minor"]=int(r["amount"])
                currencies[r["currency"]]["receipt_entries"]=int(r["entries"])
        return jsonify(
            currencies=currencies,counts={k:int(v) for k,v in counts.items()},
            definitions={
              "signed_gmv":"Sum of deal value for reward deals linked to a room with a signed sale contract. Not a completed sale.",
              "completed_gmv":"Signed sale contract plus latest verified evidence in all four stages: inspection, shipment, delivery, payment. Administrative verification, not independent bank audit.",
              "recorded_commission":"Sum of recorded commission receipt entries, not independently reconciled to bank statements.",
              "currency":"USD minor units are cents; KRW minor units are won. Never add different currencies.",
              "period":"Lifetime since database creation; no monthly attribution or imported historic Gmail deals."
            })
    except Exception:
        app.logger.exception("Private KPI read failed")
        return jsonify(error="temporarily_unavailable"),503

