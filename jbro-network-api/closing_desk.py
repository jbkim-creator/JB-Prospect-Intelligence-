"""Private pre-contract execution desk. Never writes to deal rooms, GMV or receipt ledgers."""
from datetime import date
from decimal import Decimal, InvalidOperation
import re
from flask import request, jsonify

SECTORS = {"semiconductor", "industrial", "vehicle", "infrastructure", "other"}
STAGES = {"intake", "qualified", "quote_received", "negotiation", "fee_agreed", "order_pending", "handoff", "on_hold", "lost"}
FEE_STATES = {"unconfirmed", "proposed", "written_agreement", "waived"}
CURRENCIES = {"USD", "KRW"}
KEY = re.compile(r"^[A-Z0-9][A-Z0-9_-]{2,63}$")

def normalize(data):
    if not isinstance(data, dict):
        raise ValueError("invalid_payload")
    def field(name, limit, required=False):
        val = data.get(name, "")
        if not isinstance(val, str):
            raise ValueError(name)
        val = val.strip()
        if len(val) > limit or (required and not val):
            raise ValueError(name)
        return val
    key = field("deal_key", 64, True).upper()
    sector = field("sector", 30, True)
    stage = field("stage", 30, True)
    fee_state = field("fee_state", 30, True)
    if not KEY.fullmatch(key) or sector not in SECTORS or stage not in STAGES or fee_state not in FEE_STATES:
        raise ValueError("invalid_key_sector_stage_or_fee_state")
    title = field("title", 160, True)
    source_ref = field("source_ref", 240, True)
    blocker = field("blocker", 600, True)
    action = field("next_action", 600, True)
    fee_evidence = field("fee_evidence", 240)
    handoff_ref = field("handoff_ref", 240)
    if fee_state in ("written_agreement", "waived") and not fee_evidence:
        raise ValueError("fee_evidence_required")
    if stage == "fee_agreed" and fee_state not in ("written_agreement", "waived"):
        raise ValueError("fee_agreement_required")
    if stage == "handoff" and not handoff_ref:
        raise ValueError("handoff_reference_required")
    due = field("due_date", 10)
    if due:
        try:
            parsed = date.fromisoformat(due)
            if parsed.isoformat() != due:
                raise ValueError
        except ValueError:
            raise ValueError("invalid_due_date") from None
    else:
        parsed = None
    if stage not in ("on_hold", "lost", "handoff") and parsed is None:
        raise ValueError("due_date_required")
    currency = field("currency", 3)
    value = field("indicative_value", 24)
    if bool(currency) != bool(value) or (currency and currency not in CURRENCIES):
        raise ValueError("currency_and_amount_must_be_paired")
    minor = None
    if value:
        if not re.fullmatch(r"\d{1,13}(?:\.\d{1,2})?", value):
            raise ValueError("invalid_indicative_value")
        try:
            amount = Decimal(value) * (100 if currency == "USD" else 1)
            if amount != amount.to_integral_value() or amount <= 0 or amount > 10**15:
                raise ValueError("invalid_indicative_value")
            minor = int(amount)
        except InvalidOperation:
            raise ValueError("invalid_indicative_value") from None
    revision = data.get("revision")
    if revision is not None and (type(revision) is not int or revision < 1):
        raise ValueError("invalid_revision")
    return dict(deal_key=key, sector=sector, title=title, stage=stage,
                source_ref=source_ref, blocker=blocker, next_action=action, due_date=parsed,
                fee_state=fee_state, fee_evidence=fee_evidence, handoff_ref=handoff_ref,
                currency=currency or None, indicative_value_minor=minor, revision=revision)

COLUMNS = ("deal_key", "sector", "title", "stage", "source_ref", "blocker",
           "next_action", "due_date", "fee_state", "fee_evidence", "handoff_ref",
           "currency", "indicative_value_minor")

def ensure_schema(connection):
    with connection() as conn:
        conn.execute("""
          CREATE TABLE IF NOT EXISTS closing_desk_cases (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            deal_key VARCHAR(64) UNIQUE NOT NULL,
            sector VARCHAR(30) NOT NULL,
            title VARCHAR(160) NOT NULL,
            stage VARCHAR(30) NOT NULL,
            source_ref VARCHAR(240) NOT NULL,
            blocker VARCHAR(600) NOT NULL,
            next_action VARCHAR(600) NOT NULL,
            due_date DATE,
            fee_state VARCHAR(30) NOT NULL,
            fee_evidence VARCHAR(240) NOT NULL DEFAULT '',
            handoff_ref VARCHAR(240) NOT NULL DEFAULT '',
            currency VARCHAR(3),
            indicative_value_minor BIGINT,
            revision INTEGER NOT NULL DEFAULT 1,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            CHECK (sector IN ('semiconductor','industrial','vehicle','infrastructure','other')),
            CHECK (stage IN ('intake','qualified','quote_received','negotiation','fee_agreed','order_pending','handoff','on_hold','lost')),
            CHECK (fee_state IN ('unconfirmed','proposed','written_agreement','waived')),
            CHECK ((currency IS NULL AND indicative_value_minor IS NULL) OR
                   (currency IN ('USD','KRW') AND indicative_value_minor > 0)),
            CHECK (stage IN ('on_hold','lost','handoff') OR due_date IS NOT NULL),
            CHECK (fee_state NOT IN ('written_agreement','waived') OR length(fee_evidence)>0),
            CHECK (stage<>'fee_agreed' OR fee_state IN ('written_agreement','waived')),
            CHECK (stage<>'handoff' OR length(handoff_ref)>0)
          )
        """)
        conn.execute("CREATE INDEX IF NOT EXISTS closing_desk_due_idx ON closing_desk_cases(due_date, stage)")

def serialize(row):
    item = dict(row)
    for key in ("due_date", "created_at", "updated_at"):
        if item.get(key) is not None:
            item[key] = item[key].isoformat()
    minor = item.pop("indicative_value_minor")
    item["indicative_value"] = (str(Decimal(minor) / (100 if item["currency"] == "USD" else 1))
                                if minor is not None else "")
    return item

def init(app, connection, authorized_admin):
    @app.route("/api/admin/closing-desk", methods=["GET", "POST"])
    def closing_desk_collection():
        if not authorized_admin():
            return jsonify(error="unauthorized"), 401
        if request.method == "POST":
            try:
                data = normalize(request.get_json(silent=True))
            except ValueError as exc:
                return jsonify(error=str(exc)), 400
        try:
            ensure_schema(connection)
            with connection() as conn:
                if request.method == "GET":
                    rows = conn.execute("""
                        SELECT * FROM closing_desk_cases
                        ORDER BY CASE WHEN stage IN ('lost','on_hold','handoff') THEN 1 ELSE 0 END,
                                 due_date ASC NULLS LAST, updated_at DESC
                        LIMIT 200
                    """).fetchall()
                    counts = conn.execute("SELECT stage,count(*)::int AS n FROM closing_desk_cases GROUP BY stage").fetchall()
                    return jsonify(cases=[serialize(r) for r in rows], counts={r["stage"]: r["n"] for r in counts},
                                   limit=200, definition="Indicative case information only, never completed GMV or collected fees.")
                row = conn.execute(
                    "INSERT INTO closing_desk_cases (" + ",".join(COLUMNS) + ") VALUES (" +
                    ",".join(["%s"] * len(COLUMNS)) + ") ON CONFLICT(deal_key) DO NOTHING RETURNING *",
                    tuple(data[k] for k in COLUMNS)).fetchone()
                if row is None:
                    return jsonify(error="duplicate_deal_key"), 409
                return jsonify(case=serialize(row)), 201
        except Exception:
            app.logger.warning("Closing desk collection operation failed")
            return jsonify(error="temporarily_unavailable"), 503

    @app.patch("/api/admin/closing-desk/<int:case_id>")
    def closing_desk_update(case_id):
        if not authorized_admin():
            return jsonify(error="unauthorized"), 401
        try:
            data = normalize(request.get_json(silent=True))
            if data["revision"] is None:
                raise ValueError("revision_required")
        except ValueError as exc:
            return jsonify(error=str(exc)), 400
        try:
            ensure_schema(connection)
            with connection() as conn:
                row = conn.execute(
                    "UPDATE closing_desk_cases SET " + ",".join(k + "=%s" for k in COLUMNS if k != "deal_key") +
                    ", revision=revision+1, updated_at=now() WHERE id=%s AND deal_key=%s AND revision=%s RETURNING *",
                    tuple(data[k] for k in COLUMNS if k != "deal_key") + (case_id, data["deal_key"], data["revision"])).fetchone()
                if row is None:
                    return jsonify(error="stale_revision_or_missing_case"), 409
                return jsonify(case=serialize(row))
        except Exception:
            app.logger.warning("Closing desk update failed")
            return jsonify(error="temporarily_unavailable"), 503
